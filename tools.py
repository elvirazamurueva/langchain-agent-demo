"""Пользовательский инструмент (tool) агента.

Инструмент ``get_cat_fact`` возвращает факт о породе кошки из небольшого
локального словаря. Он НЕ обращается в интернет и нужен только для
демонстрации механизма вызова инструментов агентом.
"""

from __future__ import annotations

from langchain_core.tools import tool

# Локальный словарь фактов о породах кошек.
CAT_FACTS: dict[str, str] = {
    "мейн-кун": (
        "Мейн-кун — одна из самых крупных домашних пород: взрослый кот "
        "может весить 7–12 кг, а длина тела вместе с хвостом иногда "
        "превышает 1 метр."
    ),
    "британская короткошёрстная": (
        "Британская короткошёрстная славится плотной «плюшевой» шерстью. "
        "Классическим окрасом породы считается голубой, хотя встречаются "
        "и другие."
    ),
    "сиамская": (
        "Сиамские котята рождаются почти белыми: тёмные «пойнты» на мордочке, "
        "ушах, лапах и хвосте проявляются из-за температуры — в более "
        "прохладных участках тела пигмент вырабатывается активнее."
    ),
    "сфинкс": (
        "Сфинксы кажутся полностью голыми, но на самом деле их кожа покрыта "
        "очень тонким пушком. Из-за отсутствия шерсти они теплее на ощупь."
    ),
}

# Варианты написания, которые тоже должны приводить к известной породе.
_ALIASES: dict[str, str] = {
    "мейн кун": "мейн-кун",
    "мейнкун": "мейн-кун",
    "main coon": "мейн-кун",
    "mainecoon": "мейн-кун",
    "британская": "британская короткошёрстная",
    "британец": "британская короткошёрстная",
    "британка": "британская короткошёрстная",
    "british shorthair": "британская короткошёрстная",
    "сиам": "сиамская",
    "сиамская кошка": "сиамская",
    "siamese": "сиамская",
    "sphynx": "сфинкс",
    "sphinx": "сфинкс",
}


def _normalize(breed: str) -> str:
    """Приводит название породы к виду, пригодному для поиска в словаре."""
    return " ".join(breed.strip().lower().replace("ё", "ё").split())


@tool
def get_cat_fact(breed: str) -> str:
    """Возвращает интересный факт о породе кошки.

    Используй этот инструмент, когда пользователь спрашивает факт,
    особенность или любую информацию о конкретной породе кошки.

    Args:
        breed: Название породы кошки, например "мейн-кун".
    """
    key = _normalize(breed)
    key = _ALIASES.get(key, key)

    fact = CAT_FACTS.get(key)
    if fact is None:
        available = ", ".join(sorted(CAT_FACTS))
        return (
            f"Факт о породе «{breed}» не найден. "
            f"Доступные породы: {available}."
        )

    return f"Порода «{key}»: {fact}"


# Список инструментов, который передаётся агенту.
TOOLS = [get_cat_fact]
